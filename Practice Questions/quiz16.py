# Create a script that  performs typecasting between int, float, string, and boolean values, printing the result of each conversion.

# Original values

a = 10
b = 10.5
c = "20"
d = True

# int to float
print(float(a))

# float to int
print(int(b))

# int to string
print(str(a))

# string to int
print(int(c))

# int to boolean
print(bool(a))

# boolean to int
print(int(d))

# string to boolean
print(bool(c))
